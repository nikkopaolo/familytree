import fs from "node:fs";
import { JWT } from "google-auth-library";

const keyPath = process.env.GOOGLE_APPLICATION_CREDENTIALS;
const keys = JSON.parse(fs.readFileSync(keyPath, "utf8"));
const projectId = keys.project_id;

const client = new JWT({
  email: keys.client_email,
  key: keys.private_key,
  scopes: ["https://www.googleapis.com/auth/firebase"],
});

const { token } = await client.getAccessToken();
const headers = { Authorization: `Bearer ${token}` };

let appsRes = await fetch(
  `https://firebase.googleapis.com/v1beta1/projects/${projectId}/webApps`,
  { headers }
);
let apps = await appsRes.json();

let appId = apps.apps?.[0]?.appId;
if (!appId) {
  const createRes = await fetch(
    `https://firebase.googleapis.com/v1beta1/projects/${projectId}/webApps`,
    {
      method: "POST",
      headers: { ...headers, "Content-Type": "application/json" },
      body: JSON.stringify({ displayName: "FamTree Web" }),
    }
  );
  const created = await createRes.json();
  if (!createRes.ok) {
    console.error("Create web app failed:", createRes.status, JSON.stringify(created));
    process.exit(1);
  }
  if (created.name) {
    appId = created.name.split("/").pop();
  } else if (created.response?.appId) {
    appId = created.response.appId;
  }
  if (!appId && created.name?.includes("/operations/")) {
    await new Promise((r) => setTimeout(r, 5000));
    appsRes = await fetch(
      `https://firebase.googleapis.com/v1beta1/projects/${projectId}/webApps`,
      { headers }
    );
    apps = await appsRes.json();
    appId = apps.apps?.[0]?.appId;
  }
  console.log("Web app id:", appId);
}

if (!appId) {
  console.error("Could not resolve web app id.", JSON.stringify(apps));
  process.exit(1);
}

const configRes = await fetch(
  `https://firebase.googleapis.com/v1beta1/projects/${projectId}/webApps/${appId}/config`,
  { headers }
);
const config = await configRes.json();
const env = `# Generated by scripts/migrate/fetch-web-config.mjs
NEXT_PUBLIC_FIREBASE_API_KEY=${config.apiKey}
NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=${config.authDomain}
NEXT_PUBLIC_FIREBASE_PROJECT_ID=${config.projectId}
NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=${config.storageBucket}
NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=${config.messagingSenderId}
NEXT_PUBLIC_FIREBASE_APP_ID=${config.appId}
NEXT_PUBLIC_SITE_URL=https://familytree-70db5.web.app
SUPER_ADMIN_EMAILS=katigbaknikkopaolo@gmail.com
GOOGLE_APPLICATION_CREDENTIALS=./firebase-service-account.json
`;
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
writeFileSync(resolve(".env.local"), env);
console.log("Wrote .env.local");
